  await page.get_by_role('button',name='סימון כסגורה').click()
  s=await state();l=next(l for l in s['leads'] if l['name']==name)
  await check('book and close never fabricate revenue',l['status']=='closed' and not l.get('revenueConfirmedAt'))
  await page.get_by_label('הסכום שהתקבל בשקלים').fill('850')
  await expect(page.get_by_role('button',name='אישור הכנסה בנפרד')).to_be_disabled()
  await page.get_by_role('checkbox',name='זה הסכום שהתקבל, ולא שווי פוטנציאלי').check()
  await page.get_by_role('button',name='אישור הכנסה בנפרד').click()
