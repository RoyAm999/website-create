  await page.get_by_role('button',name='תיעוד שליחה לדוגמה').click()
  await page.get_by_label('מה הפנייה ענתה?').fill('כן, מתאים לי. אשמח לתאם תור')
  await page.get_by_role('button',name='חזרה לשיחה',exact=True).click()
