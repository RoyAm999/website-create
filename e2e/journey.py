  s=await state();l=next(l for l in s['leads'] if l['name']==name)
  await check('copy does not send or count revenue',not l.get('sentAt') and not l.get('revenueConfirmedAt'))
  await expect(page.get_by_role('button',name='תיעוד שליחה לדוגמה')).to_be_disabled()
